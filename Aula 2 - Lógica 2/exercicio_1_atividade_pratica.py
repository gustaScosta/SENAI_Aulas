# Exercicio 1 - Atividade pratica com a professora

## Objetivo

# Praticar os conceitos iniciais de logica de programacao usando Python.

## Proposta

# Criar um programa que receba informacoes do usuario, processe os dados e mostre uma resposta na tela.

## Exemplo de roteiro

# 1. Pedir o nome do usuario.
# 2. Pedir a idade do usuario.
# 3. Pedir um numero.
# 4. Somar 10 ao numero informado.
# 5. Exibir os resultados na tela.

## Exemplo de codigo

# python
nome = input("Digite seu nome: ")
idade = int(input("Digite sua idade: "))
numero = int(input("Digite um numero: "))

resultado = numero + 10

print("Nome:", nome)
print("Idade:", idade)
print("Numero informado:", numero)
print("Numero + 10:", resultado)

## Conceitos usados

# - variaveis;
# - input();
# - print();
# - conversao com int();
# - entrada, processamento e saida.
